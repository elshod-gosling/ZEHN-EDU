import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, getDoc, setDoc, updateDoc, serverTimestamp, Timestamp, runTransaction, setLogLevel } from 'firebase/firestore';
import { initialAccount } from './dist/credit-policy.mjs';
import { questionBank } from './firebase/question-bank.mjs';
const env=await initializeTestEnvironment({projectId:'demo-levelup',firestore:{host:'127.0.0.1',port:8085,rules:await fs.readFile('firebase/firestore.rules','utf8')}});
setLogLevel('silent');
const google=(uid,email=uid+'@gmail.com',verified=true)=>env.authenticatedContext(uid,{email,email_verified:verified,firebase:{sign_in_provider:'google.com'}}).firestore();
const kid=google('kid'),wallet=doc(kid,'accounts/kid');
const server=serverTimestamp;
async function seed(uid,overrides={}) { await env.withSecurityRulesDisabled(async c=>{const past=Timestamp.fromMillis(Date.now()-65000);await setDoc(doc(c.firestore(),'accounts/'+uid),{...initialAccount(past),...overrides});}); }
function claim(answer='10',overrides={}) { return updateDoc(wallet,{phase:'idle',answer,credits:10,earned:10,cursor:1,lastEarnAt:server(),updatedAt:server(),...overrides}); }
try {
 await env.clearFirestore();
 await env.withSecurityRulesDisabled(async c=>{const db=c.firestore();await setDoc(doc(db,'policy/access'),{developerEmail:'owner@gmail.com'});for(const q of questionBank){await setDoc(doc(db,'questions/'+q.id),q.question);await setDoc(doc(db,'answerKeys/'+q.id),{index:q.index,cycle:Math.floor(q.index/4),answer:q.answer});}});
 await assertSucceeds(setDoc(wallet,initialAccount(server())));
 await assertFails(setDoc(doc(kid,'accounts/other'),initialAccount(server())));
 await assertFails(updateDoc(wallet,{credits:999999,updatedAt:server()}));
 await assertFails(updateDoc(wallet,{role:'developer',updatedAt:server()}));
 await assertFails(updateDoc(wallet,{startedAt:Timestamp.fromMillis(0),phase:'learning',questionId:'q0',answer:'',updatedAt:server()}));
 await assertFails(updateDoc(wallet,{phase:'learning',questionId:'q4',answer:'',startedAt:server(),updatedAt:server()}));
 await assertSucceeds(updateDoc(wallet,{phase:'learning',questionId:'q0',answer:'',startedAt:server(),updatedAt:server()}));
 await assertFails(claim(),'Early credit claim must fail');
 await seed('kid',{phase:'learning',questionId:'q0'});
 await assertFails(claim('999'),'Wrong answer must fail');
 await assertFails(claim('10',{credits:1000}),'Forged payout must fail');
 await assertSucceeds(claim());
 assert.equal((await getDoc(wallet)).data().credits,10);
 await assertFails(claim(),'Duplicate completion must fail');
 await assertFails(getDoc(doc(kid,'answerKeys/q0')));
 await assertFails(getDoc(doc(kid,'policy/access')));
 await assertFails(getDoc(doc(google('other'),'accounts/kid')));
 await assertFails(getDoc(doc(google('unverified','owner@gmail.com',false),'accounts/kid')));
 await assertFails(setDoc(doc(kid,'questions/q0'),{answer:'fake'}));
 await assertFails(setDoc(doc(kid,'answerKeys/q0'),{answer:'fake',index:0}));
 await assertFails(setDoc(doc(kid,'policy/access'),{developerEmail:'kid@gmail.com'}));
 await assertFails(getDoc(doc(env.unauthenticatedContext().firestore(),'accounts/kid')));
 const password=env.authenticatedContext('email-student',{email:'student@outlook.com',email_verified:false,firebase:{sign_in_provider:'password'}}).firestore();
 const emailWallet=doc(password,'accounts/email-student');
 await assertSucceeds(setDoc(emailWallet,initialAccount(server())));
 await assertSucceeds(getDoc(emailWallet));
 await assertSucceeds(getDoc(doc(password,'questions/q0')));
 await assertFails(getDoc(doc(password,'accounts/kid')));
 await assertFails(updateDoc(emailWallet,{role:'developer',updatedAt:server()}));
 await assertFails(updateDoc(emailWallet,{credits:999999,updatedAt:server()}));
 await assertSucceeds(updateDoc(emailWallet,{phase:'learning',questionId:'q0',answer:'',startedAt:server(),updatedAt:server()}));
 await seed('email-student',{phase:'learning',questionId:'q0'});
 await assertSucceeds(updateDoc(emailWallet,{phase:'idle',answer:'10',credits:10,earned:10,cursor:1,lastEarnAt:server(),updatedAt:server()}));
 await seed('email-student',{credits:100});
 await assertSucceeds(updateDoc(emailWallet,{credits:0,passUntil:Timestamp.fromMillis(Date.now()+300000),updatedAt:server()}));
 const impersonator=env.authenticatedContext('unverified-owner',{email:'owner@gmail.com',email_verified:false,firebase:{sign_in_provider:'password'}}).firestore();
 const impersonatorWallet=doc(impersonator,'accounts/unverified-owner');
 await assertSucceeds(setDoc(impersonatorWallet,initialAccount(server())));
 await assertFails(updateDoc(impersonatorWallet,{role:'developer',updatedAt:server()}));
 const anonymous=env.authenticatedContext('anon',{firebase:{sign_in_provider:'anonymous'}}).firestore();
 await assertFails(setDoc(doc(anonymous,'accounts/anon'),initialAccount(server())));
 await seed('kid',{credits:99});await assertFails(updateDoc(wallet,{credits:0,passUntil:Timestamp.fromMillis(Date.now()+300000),updatedAt:server()}));
 await seed('kid',{credits:100});
 await assertFails(updateDoc(wallet,{credits:0,passUntil:Timestamp.fromMillis(Date.now()+600000),updatedAt:server()}),'Cannot extend reward arbitrarily');
 await assertSucceeds(updateDoc(wallet,{credits:0,passUntil:Timestamp.fromMillis(Date.now()+300000),updatedAt:server()}));
 await assertFails(updateDoc(wallet,{credits:0,passUntil:Timestamp.fromMillis(Date.now()+300000),updatedAt:server()}),'Cannot get a second pass for free');
 await seed('kid',{credits:200,passUntil:Timestamp.fromMillis(Date.now()+300000)});await assertFails(updateDoc(wallet,{credits:100,passUntil:Timestamp.fromMillis(Date.now()+300000),updatedAt:server()}),'Active pass cannot be double-charged');
 const owner=google('owner','owner@gmail.com'),ownerWallet=doc(owner,'accounts/owner');await assertSucceeds(setDoc(ownerWallet,initialAccount(server())));await assertSucceeds(updateDoc(ownerWallet,{role:'developer',updatedAt:server()}));assert.equal((await getDoc(ownerWallet)).data().role,'developer');
 await assertFails(setDoc(doc(google('fake'),'accounts/fake'),{...initialAccount(server()),role:'developer'}));
 await seed('kid',{phase:'learning',questionId:'q0'});
 const double=await Promise.allSettled([1,2].map(()=>runTransaction(kid,async tx=>{const snap=await tx.get(wallet);const d=snap.data();if(d.phase!=='learning')throw new Error('Already collected');tx.update(wallet,{phase:'idle',answer:'10',credits:d.credits+10,earned:d.earned+10,cursor:d.cursor+1,lastEarnAt:server(),updatedAt:server()});})));
 assert.equal(double.filter(x=>x.status==='fulfilled').length,1,'Simultaneous tabs only collect once');
 assert.equal((await getDoc(wallet)).data().credits,10);
 await assertSucceeds(updateDoc(wallet,{updatedAt:server()}),'Server clock synchronization cannot mint credits');
 console.log('PASS: Firestore server timing, correct answers, exact payouts, duplicate/concurrent claims, pass spend/expiry, identity isolation, developer authorization and protected setup data.');
} finally { await env.cleanup(); }
